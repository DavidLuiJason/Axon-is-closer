import { evaluate as evaluateEngine } from '../src/tools/engines/numbers/calculator';
import { convert as convertEngine, listUnits } from '../src/tools/engines/numbers/unitConvert';
import { convertBase as convertBaseEngine } from '../src/tools/engines/numbers/baseConvert';
import { numberToWords as numberToWordsEngine } from '../src/tools/engines/numbers/numberToWords';
import { percentage as percentageEngine } from '../src/tools/engines/numbers/percentage';

let checks=0;
function assert(condition:boolean,message:string){checks++;if(!condition)throw new Error(`FAIL: ${message}`);console.log(`  OK: ${message}`);}
function close(a:number,b:number,eps=0.0001){return Math.abs(a-b)<=eps;}
const evaluate=(...args:Parameters<typeof evaluateEngine>):any=>evaluateEngine(...args);
const convert=(...args:Parameters<typeof convertEngine>):any=>convertEngine(...args);
const convertBase=(...args:Parameters<typeof convertBaseEngine>):any=>convertBaseEngine(...args);
const numberToWords=(...args:Parameters<typeof numberToWordsEngine>):any=>numberToWordsEngine(...args);
const percentage=(...args:Parameters<typeof percentageEngine>):any=>percentageEngine(...args);
function main(){
 console.log('-- calculator');
 assert(evaluate('0.1 + 0.2').ok && evaluate('0.1 + 0.2').formatted==='0.3','decimal addition avoids binary floating-point artefact');
 assert(evaluate('2^3 + 4/2').formatted==='10','power and operator precedence');
 assert(evaluate('sqrt(81)').formatted==='9','square root');
 assert(evaluate('sin(90)',{angle:'deg'}).ok && close(evaluate('sin(90)',{angle:'deg'}).value as number,1),'degree angle mode');
 assert(evaluate('sin(pi/2)').ok && close(evaluate('sin(pi/2)').value as number,1),'radian angle mode');
 assert(!evaluate('1/0').ok && evaluate('1/0').error==='division-by-zero','division by zero is typed');
 assert(!evaluate('sqrt(-1)').ok && evaluate('sqrt(-1)').error==='domain','invalid square root is a domain error');
 assert(!evaluate('2 + @').ok && evaluate('2 + @').error==='syntax','invalid character is syntax error');
 assert(!evaluate('2 + @').ok && 'position' in evaluate('2 + @') && evaluate('2 + @').position===4,'syntax error carries source position');
 assert(!evaluate('1'.repeat(513)).ok && evaluate('1'.repeat(513)).error==='too-long','oversized expression rejected');
 assert(!evaluate('').ok,'empty expression rejected');
 assert(!evaluate('😀').ok,'Unicode and emoji input rejected safely');
 assert(evaluate('abs(-7) + ceil(2.1) + floor(2.9) + round(2.5)').formatted==='15','absolute value and rounding functions');
 const valid=(expression:string,angle:'deg'|'rad',formatted:string)=>{const r=evaluate(expression,{angle});return r.ok&&r.formatted===formatted;};
 assert(valid('sin(pi)','rad','0'),'sin(pi) radians is zero');
 assert(valid('cos(pi/2)','rad','0'),'cos(pi/2) radians is zero');
 assert(valid('tan(pi)','rad','0'),'tan(pi) radians is zero');
 assert(valid('sin(180)','deg','0'),'sin(180) degrees is zero');
 assert(valid('cos(90)','deg','0'),'cos(90) degrees is zero');
 assert(valid('sin(30)','deg','0.5'),'sin(30) degrees is one half');
 assert(valid('sin(1)','rad','0.841470984808'),'sin(1) radians is rounded to 12 decimals');
 assert(evaluate('tan(90)',{angle:'deg'}).error==='domain','tan(90) degrees remains domain error');
 assert(valid('2^1000','rad',(2n**1000n).toString()),'large integer power is exact');
 assert(valid('-2^2','rad','-4'),'power precedes unary minus');
 assert(valid('(-2)^2','rad','4'),'parentheses precede power');
 assert(valid('2^-2','rad','0.25'),'negative exponent');
 assert(valid('-2^-2','rad','-0.25'),'negative exponent with unary minus');
 assert(valid('2^3^2','rad','512'),'powers associate right to left');
 assert(valid('-(2)','rad','-2'),'unary minus on parentheses');
 assert(valid('10%3','rad','1'),'percent sign is remainder');
 assert(evaluate('sqrt(2)').ok && close(evaluate('sqrt(2)').value,Math.SQRT2),'sqrt(2) remains valid');
 assert(evaluate('1/3').ok && close(evaluate('1/3').value,1/3),'one third remains valid');
 assert(evaluate('ln(e)').ok && close(evaluate('ln(e)').value,1),'ln(e) remains valid');
 console.log('-- unit conversion');
 const miles=convert(100,'km','mi');
 assert(miles.ok && close(miles.value,62.1371),'100 km converts to approximately 62.1371 miles');
 const f=convert(0,'°C','°F');
 assert(f.ok && close(f.value,32),'Celsius to Fahrenheit');
 const k=convert(32,'°F','K');
 assert(k.ok && close(k.value,273.15),'Fahrenheit to Kelvin');
 assert(!convert(1,'km','kg').ok && convert(1,'km','kg').error==='category-mismatch','cross-category conversion rejected');
 assert(!convert(Number.NaN,'m','ft').ok,'non-finite values rejected');
 assert(!convert(1,'unknown','m').ok,'unknown unit rejected');
 assert(listUnits('data').some(u=>u.symbol==='MB')&&listUnits('data').some(u=>u.symbol==='MiB'),'decimal and binary data units listed');
 assert(listUnits('length').length>=6,'units can be listed by category');
 console.log('-- number bases');
 assert(convertBase('255',10,16).ok&&convertBase('255',10,16).value==='FF','255 decimal becomes FF');
 assert(convertBase('255',10,2).ok&&convertBase('255',10,2).value==='11111111','255 decimal becomes 11111111');
 assert(convertBase('-FF',16,10).ok&&convertBase('-FF',16,10).value==='-255','negative integers supported');
 assert(convertBase('Z',36,10).ok&&convertBase('Z',36,10).value==='35','base 36 digits supported');
 assert(!convertBase('2',2,10).ok&&convertBase('2',2,10).error==='digit-out-of-range','digit outside base rejected');
 assert(!convertBase('',10,2).ok,'empty base input rejected');
 assert(!convertBase('😀',10,2).ok,'emoji base input rejected');
 assert(!convertBase('1'.repeat(10001),10,2).ok,'very large base input length capped');
 assert(convertBase('ABCDEF',16,16,{group:2}).value==='AB_CD_EF','optional grouping is deterministic');
 console.log('-- number to words');
 assert(numberToWords('1000001').ok&&numberToWords('1000001').words==='one million one','1,000,001 rendered in English');
 assert(numberToWords('999999999999999999999').ok,'maximum supported cardinal is accepted');
 assert(!numberToWords('1000000000000000000000').ok,'number beyond 10^21-1 rejected');
 assert(numberToWords('-42.05').ok&&numberToWords('-42.05').words==='negative forty-two point zero five','negative decimal reads fractional digits one by one');
 assert(numberToWords('21',{ordinal:true}).ok&&numberToWords('21',{ordinal:true}).words==='twenty-first','ordinal option');
 assert(numberToWords('-21',{ordinal:true}).ok&&numberToWords('-21',{ordinal:true}).words==='negative twenty-first','negative ordinal preserves sign');
 assert(!numberToWords('').ok,'empty number words input rejected');
 assert(!numberToWords('😀').ok,'emoji number words input rejected');
 console.log('-- percentages');
 assert(percentage('percent-of',{x:'10',y:'50'}).formatted==='5','10 percent of 50 is 5');
 assert(percentage('what-percent',{x:'2',y:'8'}).formatted==='25','2 is 25 percent of 8');
 assert(percentage('change',{a:'80',b:'100'}).formatted==='25','change from 80 to 100 is 25 percent');
 assert(percentage('adjust',{y:'200',x:'10'}).formatted==='220','increase by 10 percent');
 assert(percentage('adjust',{y:'200',x:'-10'}).formatted==='180','decrease by 10 percent');
 assert(percentage('percent-of-what',{y:'20',x:'25'}).formatted==='80','20 is 25 percent of 80');
 assert(percentage('percent-of',{x:'0.1',y:'0.2'}).formatted==='0.0002','decimal percentage is exact to output precision');
 assert(!percentage('what-percent',{x:'2',y:'0'}).ok,'zero denominator is rejected');
 assert(!percentage('percent-of',{x:'',y:'2'}).ok,'empty percentage value rejected');
 assert(!percentage('percent-of',{x:'😀',y:'2'}).ok,'emoji percentage input rejected');
 console.log(`toolsNumbers.test.ts: ${checks} checks`);
}
main();

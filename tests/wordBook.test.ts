import { createWordBook, WORD_BOOK_KEY } from '../src/brain/dictionary/wordBook';
let checks = 0;
function assert(value: boolean, message: string) { checks++; if (!value) throw new Error(`FAIL: ${message}`); }
const map = new Map<string, string>();
const storage = { getItem: (k: string) => map.get(k) ?? null, setItem: (k: string, v: string) => { map.set(k, v); }, removeItem: (k: string) => { map.delete(k); } };
let tick = 0;
const b = createWordBook({ storage, clock: () => ++tick });
assert(b.recordLookup('  CAFÉ  ').ok, 'lookup');
assert(b.recordLookup('cafe\u0301').ok, 'NFC');
assert(b.listHistory().ok && b.listHistory().history[0].count === 2, 'counts and normalization');
assert(b.addBookmark('HELLO').ok, 'bookmark');
assert(b.isBookmarked('hello').ok && (b.isBookmarked('hello').ok && b.isBookmarked('hello').ok ? (b.isBookmarked('hello') as {ok:true;value:boolean}).value : false), 'bookmark lookup');
assert(b.removeBookmark('hello').ok && !(b.isBookmarked('hello').ok && b.isBookmarked('hello').ok ? (b.isBookmarked('hello') as {ok:true;value:boolean}).value : false), 'remove bookmark');
assert(b.setNote('😀', 'emoji').ok && (b.getNote('😀').ok ? (b.getNote('😀') as {ok:true;note:string|null}).note : undefined) === 'emoji', 'emoji note');
assert(!b.setNote('😀', 'x'.repeat(1001)).ok, 'note length');
assert(b.removeNote('😀').ok && (b.getNote('😀').ok ? (b.getNote('😀') as {ok:true;note:string|null}).note : undefined) === null, 'remove note');
assert(!b.recordLookup(' ').ok && !b.addBookmark(4).ok && !b.setNote('a', null).ok, 'bad inputs');
for (let i = 0; i < 501; i++) assert(b.recordLookup(`h${i}`).ok, 'history append');
assert(b.listHistory().history.length === 500 && !b.listHistory().history.some(h => h.word === 'h0'), 'history eviction');
for (let i = 0; i < 1000; i++) assert(b.addBookmark(`b${i}`).ok, 'bookmark fill');
assert(!b.addBookmark('overflow').ok && b.addBookmark('b0').ok, 'bookmark cap');
for (let i = 0; i < 500; i++) assert(b.setNote(`n${i}`, 'a'.repeat(1000)).ok, 'note fill');
assert(!b.setNote('extra', 'a').ok && b.setNote('n0', 'new').ok, 'note cap and edit');
const full = b.exportData(); assert(full.ok, 'export');
if (!full.ok) throw new Error('export failed');
const bytes = new TextEncoder().encode(full.text).length;
const other = createWordBook();
assert(other.importData(full.text).ok && (other.exportData().ok ? (other.exportData() as { ok: true; text: string }).text : '') === full.text, 'round trip');
assert(!other.importData('garbage').ok && (other.exportData().ok ? (other.exportData() as { ok: true; text: string }).text : '') === full.text, 'atomic invalid import');
assert(!other.importData(JSON.stringify({ ...JSON.parse(full.text), schemaVersion: 2 })).ok, 'wrong import version');
assert(other.eraseAll().ok && other.listHistory().history.length === 0, 'erase');
map.set(WORD_BOOK_KEY, '{broken');
const corrupt = createWordBook({ storage });
assert(!corrupt.status().ok && [...map.keys()].some(k => k.startsWith(WORD_BOOK_KEY + '.recovery.')), 'corrupt backup');
map.set(WORD_BOOK_KEY, JSON.stringify({ schemaVersion: 2 }));
assert(!createWordBook({ storage }).status().ok, 'wrong version backup');
const throwing = { getItem(_k: string): string | null { throw Error('read'); }, setItem(_k: string, _v: string): void { throw Error('write'); }, removeItem(_k: string): void { throw Error('remove'); } };
const bad = createWordBook({ storage: throwing });
assert(!bad.status().ok && !bad.addBookmark('x').ok && !bad.eraseAll().ok, 'throwing storage');
assert(createWordBook().addBookmark('isolated').ok && createWordBook().listBookmarks().bookmarks.length === 0, 'isolated memory');
{
  const m2 = new Map<string, string>();
  const st = { getItem: (k: string) => m2.get(k) ?? null, setItem: (k: string, v: string) => { m2.set(k, v); }, removeItem: (k: string) => { m2.delete(k); } };
  const w: any = createWordBook({ storage: st });
  assert(w.setNote('__proto__', 'kept').ok, 'a note on the word __proto__ is saved');
  const again: any = createWordBook({ storage: st });
  assert(again.getNote('__proto__').note === 'kept', 'a __proto__ note survives a reload');
  const imp: any = createWordBook();
  assert(imp.importData(w.exportData().text).ok && imp.getNote('__proto__').note === 'kept', 'a __proto__ note survives export and import');
  assert((({}) as any).kept === undefined, 'no prototype pollution');
}
console.log(`wordBook: ${checks} checks passed; full book ${bytes} bytes`);
